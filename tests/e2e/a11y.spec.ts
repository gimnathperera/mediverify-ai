import path from 'node:path';

import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';

/**
 * Automated WCAG 2.1 A/AA checks with real layout and fonts (so colour contrast is included, which
 * the jsdom component tests cannot check). Fails on serious or critical violations.
 */
const PRIMARY = path.resolve(import.meta.dirname, '../../resources/primary_document_medical.pdf');
const EMAIL = process.env.SEED_USER_EMAIL ?? 'reviewer@mediverify.test';
const PASSWORD = process.env.SEED_USER_PASSWORD ?? 'Reviewer#2026';

async function expectAccessible(page: Page, label: string) {
  // Let tab fades and colour transitions finish: axe measures contrast on what is painted, and a
  // half-faded panel is not what the user ends up reading. Infinite loops (shimmer, spinners) are skipped.
  // (A string: this file is type-checked without DOM types.)
  await page.evaluate(`Promise.all(
    document.getAnimations()
      .filter((a) => a.effect?.getTiming().iterations !== Infinity)
      .map((a) => a.finished.catch(() => undefined)),
  )`);
  const { violations } = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'])
    // The PDF canvas text layer is generated by pdf.js and is not ours to fix.
    .exclude('.react-pdf__Page')
    .analyze();
  const blocking = violations
    .filter((v) => v.impact === 'serious' || v.impact === 'critical')
    .map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(', ')}`);
  expect(blocking, `${label} accessibility violations`).toEqual([]);
}

test('sign-in, documents and results pages have no serious accessibility violations', async ({
  page,
  isMobile,
}) => {
  await page.goto('/login');
  await expect(page.getByRole('button', { name: 'Sign in' })).toBeVisible();
  await expectAccessible(page, 'sign-in');

  await page.getByLabel('Email').fill(EMAIL);
  await page.getByLabel('Password', { exact: true }).fill(PASSWORD);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page).toHaveTitle(/Documents · MediVerify AI/);
  await expect(page.getByText(/Indexed: \d+ monographs/)).toBeVisible();
  await expectAccessible(page, 'documents');

  await page.getByTestId('file-input').setInputFiles(PRIMARY);
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]{36}$/);
  await expect(page.getByRole('button', { name: /Pipeline completed — 8\/8 stages/ })).toBeVisible({
    timeout: 110_000,
  });
  if (isMobile) await page.getByRole('tab', { name: 'Results' }).click();
  await expect(page.getByRole('heading', { name: 'Summary' })).toBeVisible();
  await expectAccessible(page, 'results: verification');
  await page.getByRole('tab', { name: /Critical points/ }).click();
  await expectAccessible(page, 'results: critical points');
  await page.getByRole('tab', { name: /Medications/ }).click();
  await expectAccessible(page, 'results: medications');
});

import type {
  CitationDto,
  CriticalPointDto,
  FindingDto,
  MedicationDto,
  ResultsDto,
  VerificationDto,
  VerificationStatus,
} from '@mediverify/shared';
import * as Tabs from '@radix-ui/react-tabs';
import { AlertTriangle, ChevronDown, FileSearch, Quote } from 'lucide-react';
import { useState } from 'react';

import { cn } from '../lib/utils';

import { CitationSheet } from './CitationSheet';
import { VERIFICATION_META, VerificationBadge } from './status';
import { Alert, Badge, Card, EmptyState } from './ui/primitives';

const CATEGORY_LABEL: Record<CriticalPointDto['category'], string> = {
  serious_side_effect: 'Side effect to report',
  administration_timing: 'How / when to take',
  duration_limit: 'Duration',
  follow_up: 'Follow-up',
  safety_precaution: 'Safety',
  document_discrepancy: 'Inconsistency in document',
  other: 'Other',
};

const FIELD_LABEL: Record<FindingDto['field'], string> = {
  identity: 'Monograph',
  dose: 'Dose',
  unit: 'Unit',
  route: 'Route',
  frequency: 'Frequency',
  timing: 'Timing',
  duration: 'Duration',
  indication: 'Indication',
};

function prescribed(m: MedicationDto | undefined) {
  if (!m) return '';
  const parts = [m.doseRaw, m.routeRaw ?? m.route, m.frequencyRaw, m.durationRaw].filter(
    (x): x is string => Boolean(x),
  );
  return [...new Set(parts)].join(' · ');
}

export function ResultsView({
  results,
  onShowPrimaryQuote,
}: {
  results: ResultsDto;
  onShowPrimaryQuote: (page: number | null, quote: string) => void;
}) {
  const [cite, setCite] = useState<{ c: CitationDto; heading: string } | null>(null);
  const counts = results.verifications.reduce<Record<string, number>>(
    (a, v) => ({ ...a, [v.status]: (a[v.status] ?? 0) + 1 }),
    {},
  );
  const flagged = (counts.contradicted ?? 0) + (counts.unsupported ?? 0);
  const medById = new Map(results.medications.map((m) => [m.id, m]));
  const statusByDrug = new Map(
    results.verifications.map((v) => [v.drugName.toLowerCase(), v.status]),
  );

  return (
    <div className="space-y-4">
      <Card className="p-5">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <h2 className="font-semibold text-slate-900">Summary</h2>
          {results.llm && (
            <Badge tone={results.llm.provider === 'fixture' ? 'warning' : 'neutral'}>
              Generated by {results.llm.provider}:{results.llm.model}
            </Badge>
          )}
        </div>
        {results.summary ? (
          <>
            <p className="mt-2 text-sm leading-relaxed text-slate-700">{results.summary.text}</p>
            {results.summary.warnings.length > 0 && (
              <Alert tone="warning" title="Faithfulness check warnings" className="mt-3">
                <ul className="list-disc pl-5">
                  {results.summary.warnings.map((w) => (
                    <li key={w}>{w}</li>
                  ))}
                </ul>
              </Alert>
            )}
          </>
        ) : (
          <p className="mt-2 text-sm text-slate-500">No summary was produced for this job.</p>
        )}
        <p className="mt-3 text-xs text-slate-400">
          Generated only from the uploaded document. It does not include formulary corrections.
        </p>
      </Card>

      <Tabs.Root defaultValue="issues">
        <Tabs.List
          className="flex gap-1 overflow-x-auto rounded-lg border border-slate-200 bg-white p-1"
          aria-label="Result sections"
        >
          {[
            ['issues', `Verification${flagged ? ` · ${flagged} flagged` : ''}`],
            ['critical', `Critical points · ${results.criticalPoints.length}`],
            ['meds', `Medications · ${results.medications.length}`],
          ].map(([v, label]) => (
            <Tabs.Trigger
              key={v}
              value={v!}
              className="whitespace-nowrap rounded-md px-3 py-1.5 text-sm text-slate-600 data-[state=active]:bg-brand-700 data-[state=active]:text-white"
            >
              {label}
            </Tabs.Trigger>
          ))}
        </Tabs.List>

        <Tabs.Content value="issues" className="mt-4 space-y-4">
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
            {(
              ['contradicted', 'unsupported', 'supported', 'incomplete'] as VerificationStatus[]
            ).map((s) => {
              const m = VERIFICATION_META[s];
              const Icon = m.icon;
              return (
                <div
                  key={s}
                  className={cn(
                    'rounded-lg border p-3',
                    {
                      supported: 'border-emerald-200 bg-emerald-50',
                      contradicted: 'border-rose-200 bg-rose-50',
                      unsupported: 'border-amber-200 bg-amber-50',
                      incomplete: 'border-slate-200 bg-white',
                    }[s],
                  )}
                >
                  <p className="flex items-center gap-1 text-xs font-medium text-slate-600">
                    <Icon className="h-3.5 w-3.5" aria-hidden />
                    {m.label}
                  </p>
                  <p className="text-2xl font-semibold tabular-nums">{counts[s] ?? 0}</p>
                </div>
              );
            })}
          </div>
          {results.verifications.length === 0 && (
            <EmptyState
              icon={<FileSearch className="h-8 w-8" />}
              title="No medications were verified"
            >
              No prescribed medications were extracted from this document.
            </EmptyState>
          )}
          {(['contradicted', 'unsupported', 'incomplete', 'supported'] as VerificationStatus[]).map(
            (s) => {
              const items = results.verifications.filter((v) => v.status === s);
              if (!items.length) return null;
              return (
                <section key={s} aria-labelledby={`sec-${s}`} className="space-y-3">
                  <h3
                    id={`sec-${s}`}
                    className="flex items-center gap-2 text-sm font-semibold text-slate-800"
                  >
                    <VerificationBadge status={s} />{' '}
                    <span className="font-normal text-slate-500">{VERIFICATION_META[s].help}</span>
                  </h3>
                  {items.map((v) => (
                    <VerificationCard
                      key={v.id}
                      v={v}
                      med={medById.get(v.medicationId)}
                      onCite={(c, h) => setCite({ c, heading: h })}
                    />
                  ))}
                </section>
              );
            },
          )}
        </Tabs.Content>

        <Tabs.Content value="critical" className="mt-4">
          {results.criticalPoints.length === 0 ? (
            <EmptyState
              icon={<FileSearch className="h-8 w-8" />}
              title="No critical points found"
            />
          ) : (
            <ol className="space-y-2">
              {results.criticalPoints.map((p) => {
                const formulary = p.relatedMedication
                  ? statusByDrug.get(p.relatedMedication.toLowerCase())
                  : undefined;
                return (
                  <li key={p.id}>
                    <Card
                      className={cn(
                        'p-4',
                        p.category === 'document_discrepancy' && 'border-amber-300',
                      )}
                    >
                      <div className="flex flex-wrap items-center gap-2">
                        <span className="inline-flex h-6 w-6 items-center justify-center rounded-full bg-slate-900 text-xs font-semibold text-white">
                          {p.rank}
                        </span>
                        <Badge
                          tone={
                            p.severity === 'high'
                              ? 'danger'
                              : p.severity === 'medium'
                                ? 'info'
                                : 'neutral'
                          }
                        >
                          {p.severity}
                        </Badge>
                        <Badge tone={p.category === 'document_discrepancy' ? 'warning' : 'neutral'}>
                          {p.category === 'document_discrepancy' && (
                            <AlertTriangle className="h-3 w-3" aria-hidden />
                          )}
                          {CATEGORY_LABEL[p.category]}
                        </Badge>
                        {p.relatedMedication && <Badge tone="brand">{p.relatedMedication}</Badge>}
                        {formulary && formulary !== 'supported' && (
                          <span className="text-xs text-slate-500">
                            Formulary check: <VerificationBadge status={formulary} />
                          </span>
                        )}
                      </div>
                      <p className="mt-2 text-sm text-slate-800">{p.text}</p>
                      <ul className="mt-2 space-y-1">
                        {p.sources.map((s, i) => (
                          <li key={i}>
                            <button
                              type="button"
                              onClick={() => onShowPrimaryQuote(s.page, s.quote)}
                              className="flex w-full items-start gap-2 rounded-md px-2 py-1 text-left text-xs text-slate-500 hover:bg-slate-50"
                            >
                              <Quote className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
                              <span>
                                <span className="font-medium text-slate-700">
                                  Primary doc p.{s.page ?? '?'}:
                                </span>{' '}
                                “{s.quote}”
                              </span>
                            </button>
                          </li>
                        ))}
                      </ul>
                    </Card>
                  </li>
                );
              })}
            </ol>
          )}
          <p className="mt-3 text-xs text-slate-400">
            Ranked by severity, then category (serious side effects → document inconsistencies →
            timing → duration → safety → follow-up). Restated from the uploaded document only.
          </p>
        </Tabs.Content>

        <Tabs.Content value="meds" className="mt-4">
          {results.medications.length === 0 ? (
            <EmptyState
              icon={<FileSearch className="h-8 w-8" />}
              title="No medications extracted"
            />
          ) : (
            <Card className="overflow-x-auto">
              <table className="w-full min-w-[720px] text-left text-sm">
                <thead className="border-b border-slate-200 bg-slate-50 text-xs uppercase tracking-wide text-slate-500">
                  <tr>
                    {[
                      'Medication',
                      'Dose',
                      'Route',
                      'Frequency',
                      'Timing',
                      'Duration',
                      'Indication',
                      'Source',
                    ].map((h) => (
                      <th key={h} scope="col" className="px-3 py-2 font-medium">
                        {h}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {results.medications.map((m) => (
                    <tr key={m.id} className="align-top">
                      <th scope="row" className="px-3 py-2 font-medium text-slate-900">
                        {m.drugName}
                        {m.ambiguities.length > 0 && (
                          <span
                            className="ml-1 inline-flex align-middle text-amber-600"
                            title={m.ambiguities.join('\n')}
                          >
                            <AlertTriangle
                              className="h-3.5 w-3.5"
                              aria-label={`Ambiguities: ${m.ambiguities.join('; ')}`}
                            />
                          </span>
                        )}
                      </th>
                      <td className="px-3 py-2">
                        {m.doseValue !== null ? (
                          `${m.doseValue} ${m.doseUnit ?? ''}`
                        ) : (
                          <span className="text-slate-400">not stated</span>
                        )}
                      </td>
                      <td className="px-3 py-2">
                        {m.route ?? <span className="text-slate-400">—</span>}
                      </td>
                      <td className="px-3 py-2">
                        {m.frequencyRaw ?? <span className="text-slate-400">—</span>}
                      </td>
                      <td className="px-3 py-2">
                        {m.timing?.replace('_', ' ') ?? <span className="text-slate-400">—</span>}
                      </td>
                      <td className="px-3 py-2">
                        {m.durationRaw ?? <span className="text-slate-400">—</span>}
                      </td>
                      <td className="px-3 py-2">
                        {m.indication ?? <span className="text-slate-400">—</span>}
                      </td>
                      <td className="px-3 py-2">
                        {m.sourceQuote ? (
                          <button
                            type="button"
                            className="text-brand-700 hover:underline"
                            onClick={() => onShowPrimaryQuote(m.sourcePage, m.sourceQuote!)}
                          >
                            p.{m.sourcePage ?? '?'}
                          </button>
                        ) : (
                          '—'
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </Card>
          )}
        </Tabs.Content>
      </Tabs.Root>

      <CitationSheet
        citation={cite?.c ?? null}
        heading={cite?.heading ?? ''}
        onClose={() => setCite(null)}
      />
    </div>
  );
}

function VerificationCard({
  v,
  med,
  onCite,
}: {
  v: VerificationDto;
  med: MedicationDto | undefined;
  onCite: (c: CitationDto, heading: string) => void;
}) {
  const [open, setOpen] = useState(v.status !== 'supported');
  const conflicts = v.findings.filter((f) => f.verdict === 'conflict');
  const others = v.findings.filter((f) => f.verdict !== 'conflict');
  const border = {
    supported: 'border-l-emerald-500',
    contradicted: 'border-l-rose-500',
    unsupported: 'border-l-amber-500',
    incomplete: 'border-l-slate-400',
  }[v.status];
  return (
    <Card className={cn('border-l-4 p-4', border)}>
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div>
          <p className="font-semibold text-slate-900">{v.drugName}</p>
          <p className="text-xs text-slate-500">Prescribed: {prescribed(med) || '—'}</p>
        </div>
        <VerificationBadge status={v.status} />
      </div>
      <p className="mt-2 text-sm text-slate-700">{v.summary}</p>

      {v.status === 'unsupported' && (
        <div className="mt-3 space-y-2">
          {v.similarNames.length > 0 && (
            <p className="text-xs text-amber-800">
              Similar-looking monograph name(s) not treated as a match: {v.similarNames.join(', ')}.
            </p>
          )}
          {v.coverageCitation ? (
            <button
              type="button"
              className="inline-flex items-center gap-1 text-sm text-brand-700 hover:underline"
              onClick={() => onCite(v.coverageCitation!, `${v.drugName}: reference coverage note`)}
            >
              <Quote className="h-4 w-4" aria-hidden /> Reference coverage note (
              {v.coverageCitation.section}, p.{v.coverageCitation.page})
            </button>
          ) : (
            <p className="text-xs text-slate-500">No supporting passage exists in the reference.</p>
          )}
        </div>
      )}

      {conflicts.length > 0 && (
        <ul className="mt-3 space-y-2">
          {conflicts.map((f) => (
            <FindingRow key={f.id} f={f} drug={v.drugName} onCite={onCite} />
          ))}
        </ul>
      )}
      {others.length > 0 && (
        <div className="mt-3">
          <button
            type="button"
            onClick={() => setOpen((o) => !o)}
            className="inline-flex items-center gap-1 text-xs font-medium text-slate-600 hover:text-slate-900"
            aria-expanded={open}
          >
            <ChevronDown
              className={cn('h-4 w-4 transition-transform', open && 'rotate-180')}
              aria-hidden
            />
            {open ? 'Hide' : 'Show'} {others.length} other check{others.length === 1 ? '' : 's'}
          </button>
          {open && (
            <ul className="mt-2 space-y-2">
              {others.map((f) => (
                <FindingRow key={f.id} f={f} drug={v.drugName} onCite={onCite} />
              ))}
            </ul>
          )}
        </div>
      )}
    </Card>
  );
}

const VERDICT_STYLE: Record<FindingDto['verdict'], { label: string; cls: string }> = {
  conflict: { label: 'Conflict', cls: 'bg-rose-100 text-rose-800' },
  consistent: { label: 'Consistent', cls: 'bg-emerald-100 text-emerald-800' },
  not_addressed: { label: 'Not addressed', cls: 'bg-slate-100 text-slate-600' },
  unknown: { label: 'Unverified', cls: 'bg-slate-100 text-slate-600' },
};

function FindingRow({
  f,
  drug,
  onCite,
}: {
  f: FindingDto;
  drug: string;
  onCite: (c: CitationDto, heading: string) => void;
}) {
  const st = VERDICT_STYLE[f.verdict];
  return (
    <li
      className={cn(
        'rounded-lg border p-3 text-sm',
        f.verdict === 'conflict' ? 'border-rose-200 bg-rose-50/50' : 'border-slate-200',
      )}
    >
      <div className="flex flex-wrap items-center gap-2">
        <span className="font-medium text-slate-900">{FIELD_LABEL[f.field]}</span>
        <span className={cn('rounded px-1.5 py-0.5 text-xs font-medium', st.cls)}>{st.label}</span>
        <span className="text-xs text-slate-400">
          by {f.decidedBy} · {f.confidence} confidence
        </span>
      </div>
      {(f.prescribedValue || f.referenceConstraint) && (
        <dl className="mt-1 grid gap-x-3 text-xs text-slate-600 sm:grid-cols-[auto_1fr]">
          {f.prescribedValue && (
            <>
              <dt className="text-slate-400">Prescribed</dt>
              <dd>{f.prescribedValue}</dd>
            </>
          )}
          {f.referenceConstraint && (
            <>
              <dt className="text-slate-400">Reference</dt>
              <dd>{f.referenceConstraint}</dd>
            </>
          )}
        </dl>
      )}
      <p className="mt-1 text-slate-700">{f.explanation}</p>
      {f.citation && (
        <button
          type="button"
          onClick={() => onCite(f.citation!, `${drug}: ${FIELD_LABEL[f.field]}`)}
          className={cn(
            'mt-2 inline-flex items-start gap-1 text-left text-xs hover:underline',
            f.citation.quoteValid ? 'text-brand-700' : 'text-rose-700',
          )}
        >
          <Quote className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
          <span>
            {[f.citation.monographName, f.citation.fieldLabel].filter(Boolean).join(' › ')}, p.
            {f.citation.page}: “
            {f.citation.quote.length > 140
              ? `${f.citation.quote.slice(0, 140)}…`
              : f.citation.quote}
            ”{!f.citation.quoteValid && ' (evidence rejected)'}
          </span>
        </button>
      )}
    </li>
  );
}
